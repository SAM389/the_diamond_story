class Purchase {
  final int? id;
  final int partyId;
  final int? lotId;
  final double amount;
  final String date;
  final String? notes;
  final bool autoGenerated;
  final String? autoSource;
  final String? createdAt;

  // Joined
  final String? partyName;
  final String? lotNo;

  const Purchase({
    this.id,
    required this.partyId,
    this.lotId,
    required this.amount,
    required this.date,
    this.notes,
    this.autoGenerated = false,
    this.autoSource,
    this.createdAt,
    this.partyName,
    this.lotNo,
  });

  factory Purchase.fromMap(Map<String, dynamic> map) {
    return Purchase(
      id: map['id'] as int?,
      partyId: map['party_id'] as int,
      lotId: map['lot_id'] as int?,
      amount: (map['amount'] as num?)?.toDouble() ?? 0.0,
      date: map['date'] as String? ?? '',
      notes: map['notes'] as String?,
      autoGenerated: (map['auto_generated'] as num?)?.toInt() == 1,
      autoSource: map['auto_source'] as String?,
      createdAt: map['created_at'] as String?,
      partyName: map['party_name'] as String?,
      lotNo: map['lot_no'] as String?,
    );
  }

  Map<String, dynamic> toMap() {
    return {
      if (id != null) 'id': id,
      'party_id': partyId,
      if (lotId != null) 'lot_id': lotId,
      'amount': amount,
      'date': date,
      if (notes != null) 'notes': notes,
      'auto_generated': autoGenerated ? 1 : 0,
      if (autoSource != null) 'auto_source': autoSource,
      if (createdAt != null) 'created_at': createdAt,
    };
  }
}
